CREATE TABLE IF NOT EXISTS `booking_cash_app_payments` (
  `id` bigint NOT NULL AUTO_INCREMENT,
  `bookingId` int NOT NULL,
  `bookingPaymentProfileId` int NOT NULL,
  `attempt` int NOT NULL,
  `stripePaymentIntentId` varchar(255) NOT NULL,
  `idempotencyKey` varchar(160) NOT NULL,
  `returnToken` varchar(36) NOT NULL,
  `amountCents` int NOT NULL,
  `currency` varchar(3) NOT NULL,
  `status` varchar(32) NOT NULL,
  `cardBrand` varchar(40),
  `cardLast4` varchar(4),
  `paidAt` bigint,
  `failureCode` varchar(128),
  `failureMessage` text,
  `createdAt` datetime(3) NOT NULL,
  `updatedAt` datetime(3) NOT NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uq_booking_cash_app_payment_intent` (`stripePaymentIntentId`),
  UNIQUE KEY `uq_booking_cash_app_idempotency` (`idempotencyKey`),
  UNIQUE KEY `uq_booking_cash_app_return_token` (`returnToken`),
  UNIQUE KEY `uq_booking_cash_app_booking_attempt` (`bookingId`, `attempt`),
  KEY `idx_booking_cash_app_profile_status` (`bookingPaymentProfileId`, `status`),
  KEY `idx_booking_cash_app_booking_status` (`bookingId`, `status`)
);
