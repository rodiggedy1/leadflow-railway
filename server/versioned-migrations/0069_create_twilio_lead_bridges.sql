CREATE TABLE IF NOT EXISTS `twilio_lead_bridges` (
  `id` bigint NOT NULL AUTO_INCREMENT,
  `bridgeId` varchar(64) NOT NULL,
  `idempotencyKey` varchar(96) NOT NULL,
  `sessionId` int NULL,
  `leadPhone` varchar(30) NOT NULL,
  `leadName` varchar(255) NOT NULL,
  `state` varchar(40) NOT NULL,
  `officeCallSid` varchar(64) NULL,
  `customerCallSid` varchar(64) NULL,
  `conferenceSid` varchar(64) NULL,
  `customerCallStartedAt` datetime(3) NULL,
  `confirmedAt` datetime(3) NULL,
  `completedAt` datetime(3) NULL,
  `failureCode` varchar(80) NULL,
  `failureMessage` varchar(512) NULL,
  `createdAt` datetime(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updatedAt` datetime(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (`id`),
  UNIQUE KEY `uq_tlb_bridge_id` (`bridgeId`),
  UNIQUE KEY `uq_tlb_idempotency_key` (`idempotencyKey`),
  KEY `idx_tlb_state` (`state`),
  KEY `idx_tlb_session` (`sessionId`),
  KEY `idx_tlb_customer_call` (`customerCallSid`)
);
